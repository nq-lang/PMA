"""
engine/market_sim.py
=====================

MarketSimulator: deterministically fabricates a self-consistent, purely
SIMULATED snapshot of an underlying's price/volatility environment, given
only a ticker string and an optional random seed.

**No network calls. No real market data. Everything here is synthetic**,
generated by a seeded `numpy.random.Generator` so that the *same* ticker +
seed always reproduces the *same* snapshot (deterministic, testable). This
is a deliberate design choice per the project spec: the app must never be
mistaken for a live data feed, and the numbers must still be internally
consistent (e.g., day range brackets spot, 52-week range brackets the day
range, moving averages sit plausibly relative to spot) so the UI looks and
behaves like a real terminal without pretending to be one.

The only place true wall-clock randomness is allowed to leak in (per spec
§5.1) is the cosmetic "recent trades / flow" tape rows, which exist purely
for visual flavor in a sidebar feed and are explicitly *not* required to
be interactive or reproducible in the same way as the core pricing
snapshot. Even so, by default we still seed the flow tape from the same
seeded RNG for full reproducibility in tests; a caller can opt into
wall-clock-seeded "live-look" flavor rows for the running app if desired.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field

import numpy as np


def _seed_from_ticker(ticker: str, seed: int | None) -> int:
    """Derive a deterministic 32-bit integer seed from a ticker string
    (and an optional explicit seed override). Using a hash of the ticker
    means every ticker gets its own stable, internally-consistent universe
    of fabricated numbers, but different tickers don't collide or look
    identical to each other.
    """
    if seed is not None:
        return int(seed) & 0xFFFFFFFF
    digest = hashlib.sha256(ticker.strip().upper().encode("utf-8")).digest()
    return int.from_bytes(digest[:4], byteorder="big")


@dataclass(frozen=True)
class UnderlyingSnapshot:
    """A self-consistent, fabricated snapshot of an underlying's price
    environment. All fields are synthetic (see module docstring)."""

    ticker: str
    company_name: str
    price: float
    day_low: float
    day_high: float
    year_low: float
    year_high: float
    market_cap: float  # in dollars (not billions) for easy formatting downstream
    ma_50: float
    ma_200: float
    base_iv: float  # base at-the-money, ~30 DTE implied volatility (decimal, e.g. 0.635)
    risk_free_rate: float  # decimal, e.g. 0.045 for 4.5%
    dividend_yield: float  # decimal, e.g. 0.0 for a non-dividend payer


# A small deterministic pool of plausible company-name suffixes/styles, used
# only to make the fabricated "company_name" field look sensible for any
# arbitrary ticker the user types in. This is NOT a real ticker lookup.
_NAME_TEMPLATES = [
    "{t} Inc.",
    "{t} Corporation",
    "{t} Holdings, Inc.",
    "{t} Technologies, Inc.",
    "{t} Group plc",
    "{t} & Co.",
]


class MarketSimulator:
    """Deterministically fabricates an internally-consistent market
    environment for a given ticker string.

    Usage:
        sim = MarketSimulator("TSLA", seed=None)  # seed derived from ticker
        snap = sim.snapshot()
        iv = sim.implied_vol(strike=310, spot=snap.price, dte_days=45)
        rows = sim.flow_tape(snap, n=12)

    Reproducibility: constructing two `MarketSimulator("TSLA")` instances
    (no explicit seed) always yields the same `snapshot()` and the same
    `implied_vol(...)` surface, because the seed is derived from the
    ticker string itself. Passing an explicit `seed` overrides that and
    lets a caller get a *different* fabricated universe for the same
    ticker (e.g., a "reroll" button), while remaining reproducible for
    that (ticker, seed) pair.
    """

    def __init__(self, ticker: str, seed: int | None = None):
        self.ticker = ticker.strip().upper() or "AAPL"
        self._seed = _seed_from_ticker(self.ticker, seed)
        self._rng = np.random.default_rng(self._seed)
        self._snapshot: UnderlyingSnapshot | None = None

    # -- Snapshot ----------------------------------------------------------

    def snapshot(self) -> UnderlyingSnapshot:
        """Return the (cached, deterministic) fabricated underlying snapshot."""
        if self._snapshot is not None:
            return self._snapshot

        rng = np.random.default_rng(self._seed)  # fresh stream, independent of flow tape draws

        # Spot price: log-uniform-ish over a plausible equity range so
        # different tickers get visually distinct price levels.
        log_price = rng.uniform(np.log(8.0), np.log(650.0))
        price = float(np.round(np.exp(log_price), 2))

        # Day range brackets spot, as a small percentage band.
        day_half_range_pct = float(rng.uniform(0.005, 0.025))
        day_low = round(price * (1 - day_half_range_pct * rng.uniform(0.3, 1.0)), 2)
        day_high = round(price * (1 + day_half_range_pct * rng.uniform(0.3, 1.0)), 2)
        # Ensure spot sits within [day_low, day_high] (it may be the day's
        # current extreme, matching real tickers where price == day_high
        # or day_low is common intraday).
        day_low = min(day_low, price)
        day_high = max(day_high, price)

        # 52-week range brackets the day range with a wider, regime-like band.
        annual_vol_factor = float(rng.uniform(0.35, 1.4))  # proxy for how volatile the name is
        year_low = round(day_low * np.exp(-annual_vol_factor * rng.uniform(0.3, 0.9)), 2)
        year_high = round(day_high * np.exp(annual_vol_factor * rng.uniform(0.3, 0.9)), 2)
        year_low = min(year_low, day_low * 0.999)
        year_high = max(year_high, day_high * 1.001)

        # Moving averages sit plausibly relative to spot: 50-day closer to
        # spot than 200-day, both within the 52-week range, and their
        # relative order (50 above/below 200 = "trend") is randomized.
        trend_up = bool(rng.uniform() > 0.5)
        if trend_up:
            ma_50 = round(price * rng.uniform(0.90, 0.99), 2)
            ma_200 = round(ma_50 * rng.uniform(0.85, 0.98), 2)
        else:
            ma_50 = round(price * rng.uniform(1.01, 1.10), 2)
            ma_200 = round(ma_50 * rng.uniform(1.02, 1.15), 2)
        ma_50 = float(np.clip(ma_50, year_low, year_high))
        ma_200 = float(np.clip(ma_200, year_low, year_high))

        # Market cap: fabricate a share count consistent with the price to
        # produce a plausible-looking cap, purely cosmetic.
        shares_outstanding = float(rng.uniform(0.2e9, 8e9))
        market_cap = round(price * shares_outstanding, 0)

        # Base IV: higher-vol "regime" tickers (per annual_vol_factor) get
        # a higher base IV, so the fabricated numbers hang together instead
        # of an erratic-52-week-range stock showing a suspiciously calm IV.
        base_iv = float(np.clip(0.18 + 0.35 * (annual_vol_factor - 0.35) / (1.4 - 0.35), 0.12, 1.20))
        base_iv = round(base_iv + rng.normal(0, 0.03), 4)
        base_iv = float(np.clip(base_iv, 0.10, 1.50))

        risk_free_rate = round(float(rng.uniform(0.03, 0.05)), 4)
        # Most names are non-dividend-payers in this simulated universe;
        # a minority get a small simulated yield.
        dividend_yield = 0.0 if rng.uniform() > 0.35 else round(float(rng.uniform(0.002, 0.035)), 4)

        name_template = _NAME_TEMPLATES[int(rng.integers(0, len(_NAME_TEMPLATES)))]
        company_name = name_template.format(t=self.ticker)

        self._snapshot = UnderlyingSnapshot(
            ticker=self.ticker,
            company_name=company_name,
            price=price,
            day_low=day_low,
            day_high=day_high,
            year_low=year_low,
            year_high=year_high,
            market_cap=market_cap,
            ma_50=ma_50,
            ma_200=ma_200,
            base_iv=base_iv,
            risk_free_rate=risk_free_rate,
            dividend_yield=dividend_yield,
        )
        return self._snapshot

    # -- IV surface (skew + term structure) --------------------------------

    def implied_vol(self, strike: float, spot: float, dte_days: float) -> float:
        """Fabricated IV for a given strike/spot/DTE, built from the
        snapshot's base_iv plus a smooth skew (higher IV further
        out-of-the-money, classic "smile/skew" shape) and a simple term
        structure (short-dated options carry a modest extra-vol bump,
        long-dated options settle toward base_iv). Deterministic given the
        snapshot (i.e., given the ticker/seed) — same inputs always
        produce the same IV, so re-rendering the chart with unchanged
        strikes is stable and doesn't jitter.

        This is NOT a real vol surface calibration — it is a smooth,
        plausible-looking synthetic function, intentionally simple so the
        UI can demonstrate "different strikes/expirations get different
        IV" (spec §5.1) without pretending to model real skew dynamics.
        """
        snap = self.snapshot()
        base = snap.base_iv

        moneyness = np.log(np.maximum(strike, 1e-6) / np.maximum(spot, 1e-6))
        # Skew: a downside (put-side, moneyness<0) skew bump plus a smaller
        # upside bump, both symmetric-ish but with more curvature on the
        # downside (equity-index-style skew shape).
        downside_skew = 0.55 * np.maximum(-moneyness, 0.0) ** 1.35
        upside_skew = 0.22 * np.maximum(moneyness, 0.0) ** 1.35
        skew_component = downside_skew + upside_skew

        # Term structure: short-dated (< ~14 DTE) options get a mild extra
        # bump (event/gamma risk proxy); very long-dated options taper
        # slightly below base as the term structure flattens.
        dte = max(float(dte_days), 0.5)
        term_bump = 0.06 * np.exp(-dte / 10.0) - 0.03 * (1 - np.exp(-dte / 250.0))

        iv = base + skew_component + term_bump
        return float(np.clip(iv, 0.05, 2.5))
